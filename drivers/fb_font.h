static inline unsigned char fb_cp_to_glyph(unsigned short cp) {
    int lo = 0, hi = FB_UNICODE_MAP_SIZE - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        if (fb_unicode_map[mid].cp == cp)
            return fb_unicode_map[mid].glyph;
        if (fb_unicode_map[mid].cp < cp)
            lo = mid + 1;
        else
            hi = mid - 1;
    }
    return 0; // replacement character (space)
}

